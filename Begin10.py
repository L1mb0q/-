a = float(input(" Введите число a: "))
b = float(input(" Введите число b: "))
a2 = a ** 2
b2 = b ** 2
Сумма = a2 + b2
Разность = a2 - b2
Произведение = a2 * b2
Частность = a2 / b2
print(f" Сумма = {Сумма}")
print(f"Разность = {Разность}")
print(f"Произведние = {Произведение}")
print(f"Частность = {Частность}")