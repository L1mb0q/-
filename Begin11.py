a = float(input(" Введите число a: "))
b = float(input(" Введите число b: "))
a2 = abs(a)
b2 = abs(b)
Сумма = a2 + b2
Разность = a2 - b2
Произведение = a2 * b2
Частность = a2 / b2
print(f"Сумма модулей = {Сумма}")
print(f"Разность модулей = {Разность}")
print(f"Произведние модулей = {Произведение}")
print(f"Частность модулей = {Частность}")